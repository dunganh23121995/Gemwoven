"""Pack Nori's own form-skill FX (src/forms-nori.js) into runtime strips: assets/fx/heroes/earth/<name>.webp + fx.json.

Input: <name>/raw-sheet.png, a 2x4 sheet generated by codex_image_gen.py (prompt in <name>/prompt-used.txt), keyed with
generate2dsprite.py process (its raw-sheet-clean.png in <name>/key). Every effect grows from one ground point that the
prompt fixes in the cell; each cell is cut on the grid, magenta spill on the outlines is neutralised, and the frames are
shifted by whole pixels only if the model's ground point drifted (measured per effect), never redrawn or warped.
fx.json: count, frameDuration, aspect (w/h), foot (ground line as a share of the cell height), anchorX."""
import json, subprocess, sys
from pathlib import Path
import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = Path(__file__).resolve().parent
PROC = 'C:/Users/dungc/.codex/skills/generate2dsprite/scripts/generate2dsprite.py'
CELL = 320
# name: (frame ms, ground anchor kind)
FX = {'tree': (95, 'trunk'), 'roots': (80, 'fixed'), 'quake': (60, 'fixed')}


def keyed(name):
    key = ROOT / name / 'key'
    if not (key / 'raw-sheet-clean.png').exists():
        subprocess.run([sys.executable, PROC, 'process', '--input', str(ROOT / name / 'raw-sheet.png'), '--target', 'asset', '--mode', 'fx', '--output-dir', str(key),
                        '--rows', '4', '--cols', '2', '--cell-size', '320', '--fit-scale', '1', '--align', 'center', '--scale-strategy', 'preserve', '--component-mode', 'all'], check=True, capture_output=True)
    return Image.open(key / 'raw-sheet-clean.png').convert('RGBA')


def despill(a):
    """FX hold no pink/violet: pull any magenta cast (red and blue above green) to neutral, fading strong edge spill."""
    r, g, b, al = a[..., 0], a[..., 1], a[..., 2], a[..., 3]
    sus = (b > g + 6) & (r > g + 6)
    k = np.clip((np.minimum(r, b) - g) / 120, 0, 1)
    edge = ndimage.binary_dilation(al < 200, iterations=2)
    a[..., 3] = np.where(sus & edge, al * (1 - .7 * k), al)
    a[..., 0] = np.where(sus, g + (r - g) * .5, r); a[..., 2] = np.where(sus, g + (b - g) * .2, b)
    return a


meta = {}
for name, (ms, kind) in FX.items():
    if not (ROOT / name / 'raw-sheet.png').exists(): continue
    sheet = keyed(name); W, H = sheet.width / 2, sheet.height / 4
    cells = [np.asarray(sheet.crop((round(c * W), round(r * H), round((c + 1) * W), round((r + 1) * H))).resize((CELL, CELL), Image.LANCZOS), dtype=np.float32) for r in range(4) for c in range(2)]
    # ground point per frame: the trunk's base (lowest solid run in the central columns) or the prompt's fixed point
    shifts = []
    if kind == 'trunk':
        base = []
        for a in cells:
            m = a[..., 3] > 160; cen = m[:, int(CELL * .3):int(CELL * .7)]
            y = np.where(cen.sum(1) >= 4)[0].max(); xs = np.where(cen[y - 8:y + 1].any(0))[0] + int(CELL * .3)
            base.append(((xs.min() + xs.max()) / 2, y))
        bx, by = np.median([b[0] for b in base]), np.median([b[1] for b in base])
        shifts = [(int(round(bx - x)), int(round(by - y))) for x, y in base]
        foot, ax = by / CELL, bx / CELL
    else:
        shifts = [(0, 0)] * 8
        foot, ax = {'roots': (.70, .5), 'quake': (.775, .515)}[name]
    strip = Image.new('RGBA', (CELL * 8, CELL))
    for i, (a, (dx, dy)) in enumerate(zip(cells, shifts)):
        im = Image.fromarray(despill(a.copy()).clip(0, 255).astype('uint8'), 'RGBA')
        strip.alpha_composite(im, (CELL * i + dx, dy)) if dx >= 0 and dy >= 0 else strip.paste(im, (CELL * i + dx, dy), im)
    strip.save(ROOT / f'{name}.webp', 'WEBP', quality=92, alpha_quality=100, method=6)
    meta[name] = {'file': f'assets/fx/heroes/earth/{name}.webp', 'count': 8, 'frameDuration': ms, 'aspect': 1, 'foot': round(float(foot), 4), 'anchorX': round(float(ax), 4)}
    print(name, 'ground', meta[name]['foot'], 'shifts', shifts)
(ROOT / 'fx.json').write_text(json.dumps(meta, indent=2) + '\n', encoding='utf-8')
